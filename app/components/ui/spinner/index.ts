import type { VariantProps } from 'class-variance-authority'
import { cva } from 'class-variance-authority'

export { default as Spinner } from './Spinner.vue'

/**
 * Спиннер — мастер `Spinner` `134:1768`, спека `133:1563`, тёмный набор `6976:58899`.
 *
 * Индикатор **неопределённого** ожидания: конца у него нет. Обратный отсчёт с
 * известным концом — это `Timer` `6344:55714`, отдельный компонент.
 *
 * ## Матрица целиком: 10 вариантов
 *
 * `Color` (2) × `Size` (5) — полный крест. Цветовая ось здесь всего из двух
 * колонок, брендовой и белой, и обе несут роль: белая — это спиннер поверх
 * тёмного или цветного, то есть `inverse`. Роли `success` и прочие у спиннера
 * не нарисованы и не выдумываются.
 *
 * ## Кольцо и его толщина
 *
 * Внутри каждого варианта — один вектор с **угловой (конической) заливкой**.
 * Стопы сняты с мастера: `#4480f3` на **12%** → `#4480f3` на 100%. То есть
 * кольцо не исчезает совсем, а гаснет до двенадцати процентов — того же уровня,
 * на котором сидит подложка `Timer`.
 *
 * Толщина кольца **непропорциональна стороне** — замерена по экспорту мастера,
 * а не выведена долей:
 *
 * | сторона | 16 | 20 | 32 | 48 | 72 |
 * |---|---|---|---|---|---|
 * | кольцо | 4 | 4 | 4 | 5 | 6 |
 *
 * Это та же логика, что у обводки пикт Атома: толщина держится постоянной на
 * мелких размерах и подрастает на крупных. Пропорциональное кольцо на 16px было
 * бы вдвое тоньше эталона.
 */
export const spinnerVariants = cva('inline-block shrink-0 rounded-full', {
  variants: {
    variant: {
      default: 'text-primary',
      /** Белая колонка мастера: спиннер поверх тёмного или цветного. */
      inverse: 'text-primary-foreground',
    },
    size: {
      xs: 'size-4',
      sm: 'size-5',
      md: 'size-8',
      lg: 'size-12',
      xl: 'size-18',
    },
  },
  defaultVariants: {
    variant: 'default',
    size: 'md',
  },
})

/** Толщина кольца в пикселях, по размеру. Замерено по экспорту мастера `134:1768`. */
export const spinnerRing: Record<NonNullable<SpinnerVariants['size']> & string, number> = {
  xs: 4,
  sm: 4,
  md: 4,
  lg: 5,
  xl: 6,
}

export type SpinnerVariants = VariantProps<typeof spinnerVariants>
