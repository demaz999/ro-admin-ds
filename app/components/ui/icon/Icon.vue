<script setup lang="ts">
import { computed } from 'vue'
import { icons, type IconName } from './icons'

/**
 * Единый компонент иконки: имя без размера, размер — проп.
 * Правило нейминга из CLAUDE.md — `delete`, `search`, `copy`, а не `24_ic_search`.
 *
 * Цвет не задаётся: глиф всегда красится `currentColor`, то есть наследует цвет
 * текста родителя. У Атома цвет иконки в поле совпадает с цветом текста
 * состояния — в покое плейсхолдерный, под наведением и фокусом цвет значения.
 *
 * **Глиф заполняет бокс по доминирующей стороне.** viewBox строится по плотным
 * границам контура, а не по исходному квадрату 960 Material: иначе видимый глиф
 * оказывается на четверть мельче эталона при одинаковом боксе. Вторая сторона
 * идёт по натуральной пропорции глифа — квадратная пикта заполняет квадрат, а
 * шеврон остаётся широким и низким, как у Атома. Разбор — в `icons.ts`.
 */
const props = withDefaults(defineProps<{
  name: IconName
  /** Доминирующая сторона глифа в px. Лесенка наша, размер 24 остаётся дефолтом. */
  size?: number
  /**
   * Оптическая поправка: доля бокса, которую занимает глиф. По умолчанию 1 —
   * глиф заполняет бокс, как пикта Атома.
   *
   * Нужна там, где рисунок глифа тяжелее соседей при равном боксе. Диагональный
   * крестик — как раз такой случай: сплошной X даёт заметно больше чернил, чем
   * контурная лупа того же размера.
   *
   * **Точечная настройка, а не общая.** Коробка не меняется, раскладка не едет:
   * масштабируется только содержимое. Ставится в месте применения, чтобы одна
   * и та же иконка могла быть плотной в одном контексте и лёгкой в другом.
   */
  scale?: number
}>(), { size: 24, scale: 1 })

const glyph = computed(() => {
  const def = icons[props.name]

  /**
   * Имени нет в наборе — падаем понятно. Без этой проверки ошибка выглядит как
   * «Cannot read properties of undefined (reading 'box')» и не называет ни
   * иконку, ни место: искать приходится по всему дереву.
   */
  if (!def) {
    throw new Error(
      `Icon: глифа «${props.name}» нет в наборе. Доступны: ${Object.keys(icons).join(', ')}`,
    )
  }

  const [x, y, w, h] = def.box
  const long = Math.max(w, h)
  const s = props.scale

  // viewBox раздувается вокруг центра: бокс остаётся прежним, глиф внутри мельче.
  const vw = w / s
  const vh = h / s

  return {
    viewBox: `${x - (vw - w) / 2} ${y - (vh - h) / 2} ${vw} ${vh}`,
    width: (w / long) * props.size,
    height: (h / long) * props.size,
  }
})
</script>

<template>
  <svg
    data-slot="icon"
    :width="glyph.width"
    :height="glyph.height"
    :viewBox="glyph.viewBox"
    fill="currentColor"
    aria-hidden="true"
    focusable="false"
    class="shrink-0"
  >
    <path :d="icons[name].d" />
  </svg>
</template>
