/**
 * Поле формулы — роль «текст с переменными». Такт 62; мини-ворота владельца 2026-10-03 — да (`docs/scheme-edit.md`,
 * раздел 8, карточка 7). Мастера в ките 1 нет: источник вида — фрейм поля формулы макета страницы схемы
 * `33230:4139` (файл `U829JoK7KMZV8do3KNkWBh`); поведение — `spec-r2.md` §4 и `spec-audit.md`, «Контекстная помощь и
 * превью».
 *
 * ## Значение
 *
 * `v-model` — строка: свободный текст и переменные в виде `{Группа:ключ}`, например `Осмотр {Car:vin}`. Список
 * известных переменных — проп `variables`: `{ value: 'Car:vin', label: 'VIN', group: 'Автомобиль' }`. Переменная вне
 * списка остаётся в значении и рисуется чипом в состоянии ошибки с собственным ключом вместо подписи.
 *
 * ## Вид
 *
 * | что | кит | макет |
 * |---|---|---|
 * | тело: высота от 40, радиус 8, поля 8 | `min-h-10 rounded-md p-2`, роли поля `--field`, `--field-hover` | `33230:4139` — 40, радиус 8, поля 8; заливка белая с рамкой `#ccdef5` — поле кита 1, у кита поле залитое |
 * | зазор частей 4 | `gap-1` | `33230:4139` — 4 |
 * | чип-переменная: высота 24, радиус полный, поля 6 / 6 / 6 / 12, зазор 4 | `h-6 rounded-full pl-3 pr-1.5 gap-1` | `33230:4140` — 24, радиус 20, `6,6,6,12`, 4 |
 * | чип: заливка и текст | `--secondary`, `--primary`; 12/16 bold | `33230:4140` — `#edf3fc`; `33230:4141` — Bold 12 `#0059cf` |
 * | крестик чипа: коробка 12 | кнопка 12, глиф `close` 8 | `33230:4142` — 12×12 |
 * | чип ошибки | `--destructive-surface`, `--destructive-strong` | в макете нет — роли ошибки кита |
 * | кнопка «Переменная»: высота 24, контур 1, поля 6 / 12 / 6 / 6, плюс 12 | `border-foreground-secondary`, 12/16 bold `--foreground-secondary` | `33230:4145` — контур `#567499`; `33230:4149` — Bold 12 `#567499` |
 * | превью: подпись 12/16 bold, значение 15/20 | `text-2xs` `--foreground-secondary`, `text-sm` `--foreground` | `33230:4478` — Bold 12 `#567499`; `33230:4479` — Regular 15/20 `#0e1e33` |
 *
 * ## Поведение
 *
 * - переменная вставляется в место курсора кнопкой «Переменная» (список с группами) и удаляется целиком — крестиком,
 *   Backspace или Delete;
 * - стрелки влево и вправо проходят чип целиком;
 * - вставка из буфера и набор текста вида `{Группа:ключ}` превращаются в чипы;
 * - Enter строку не переносит: формула однострочная, длинная переносится по ширине.
 *
 * ## Реализация
 *
 * Примитива Reka под текст с атомарными вставками нет. Тело — редактируемая область (`contenteditable`), чипы —
 * нередактируемые узлы внутри неё; узлы области строит сам компонент, шаблон Vue их не трогает — иначе правка
 * браузера и перерисовка Vue спорят за одни и те же текстовые узлы.
 *
 * ## Состояния
 *
 * Покой, наведение (`--field-hover`), фокус (кольцо кита), `invalid` (заливка `--field-error`), `disabled`
 * (прозрачность `--opacity-disabled`, правка выключена).
 */
export interface FormulaVariable {
  /** Ключ в значении: `Группа:ключ`. */
  value: string
  /** Подпись чипа. */
  label: string
  /** Заголовок группы в списке вставки. */
  group?: string
}

/**
 * Переменная в строке формулы: `{Группа:ключ}`. Выражение глобальное — только для `matchAll` и `replace`: у `test`
 * глобального выражения свой `lastIndex`, и следующий `matchAll` начал бы поиск с него.
 */
export const FORMULA_TOKEN = /\{([^{}\s:]+:[^{}\s]+)\}/g
/** Есть ли в тексте переменная — проверка без состояния. */
export const hasFormulaToken = (text: string) => /\{[^{}\s:]+:[^{}\s]+\}/.test(text)

/** Результат подстановки: значения известных переменных вместо `{Группа:ключ}`; неизвестная остаётся как есть. */
export function formulaPreview(formula: string, values: Record<string, string>): string {
  return formula.replace(FORMULA_TOKEN, (token, key: string) => values[key] ?? token)
}
