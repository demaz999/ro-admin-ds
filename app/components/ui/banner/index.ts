import type { VariantProps } from 'class-variance-authority'
import { cva } from 'class-variance-authority'

export { default as Banner } from './Banner.vue'

/**
 * Промо-плашка — мастер `Announcement` `149:1663`, спека `144:1550`.
 *
 * Имя `Announcement` в код не идёт: «объявление» не говорит о роли. Это
 * карточка-анонс с картинкой, заголовком и подписью — в словаре shadcn это
 * `Banner`.
 *
 * ## Матрица целиком: 4 варианта
 *
 * `Size` × `Breakpoint` — полный крест. **Обе оси меняют одно и то же:** кегли
 * заголовка и подписи вместе с габаритом.
 *
 * | вариант | габарит | заголовок | подпись |
 * |---|---|---|---|
 * | крупный · широкий | 294×300 | 20 Bold | 16 Regular |
 * | крупный · узкий | 272×262 | **16 Bold** | **13 Regular** |
 * | мелкий · широкий | 212×224 | **16 Bold** | **13 Regular** |
 * | мелкий · узкий | 153×168 | 13 Bold | 10 Regular |
 *
 * Средние две строки **совпадают по типографике** и различаются только
 * габаритом. То есть четыре варианта дают всего **три ступени текста**, и одна
 * из них достижима двумя путями.
 *
 * В коде поэтому одна ось — `size` с тремя ступенями, а не две по два значения:
 * `Breakpoint` описывает ширину окна, о которой компонент не знает. То же
 * решение, что у `NavigationTile`.
 *
 * Габариты не переносятся по той же причине: у Figma нет резиновой раскладки,
 * и четыре коробки — это снимки, а не размеры. Радиуса и заливки у мастера нет.
 *
 * Все три ступени легли в шкалу кита точно: 20/16/13 у заголовка, 16/13/10 у
 * подписи. Расширять шкалу не потребовалось — редкий случай в этом переносе.
 */
export const bannerVariants = cva('flex w-full flex-col gap-2', {
  variants: {
    size: {
      lg: '',
      md: '',
      sm: '',
    },
  },
  defaultVariants: { size: 'md' },
})

/** Кегли заголовка и подписи по ступени. Сняты с мастера поштучно. */
export const bannerText = {
  lg: { title: 'text-xl', hint: 'text-base' },
  md: { title: 'text-base', hint: 'text-xs' },
  sm: { title: 'text-xs', hint: 'text-3xs' },
} as const

export type BannerVariants = VariantProps<typeof bannerVariants>
