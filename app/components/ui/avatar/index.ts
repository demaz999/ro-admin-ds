import type { VariantProps } from 'class-variance-authority'
import { cva } from 'class-variance-authority'

export { default as Avatar } from './Avatar.vue'

/**
 * Аватар — мастер `Avatar` `3488:24229`, спека `3488:24266`, тёмный набор `4010:36490`.
 *
 * ## Матрица мастера: 30 вариантов
 *
 * `Type` (3) × `Size` (6) × `Color` (2) — но крест неполный: у фотографии
 * цвета нет, её заливка и есть изображение. 6 × (2 + 2 + 1) = 30.
 *
 * Две цветовые колонки здесь **не роли, а плотность заливки**: брендовый на
 * 100% и он же на 12%. Семантики в них нет, поэтому граница решения 23 к ним не
 * применяется — это `variant` вида `solid` / `soft`, а не `success` / `warning`.
 * Содержимое идёт за заливкой: на плотной оно белое, на мягкой брендовое.
 *
 * ## Ступени размера непропорциональны
 *
 * Ни глиф, ни кегль не масштабируются долей от стороны — обе лестницы сняты
 * поштучно:
 *
 * | сторона | 24 | 32 | 40 | 56 | 72 | 104 |
 * |---|---|---|---|---|---|---|
 * | иконка | 16 | 16 | 16 | 20 | 32 | 56 |
 * | буква | 13/16 | 16/20 | 20/24 | 28/32 | 40/44 | 56/56 |
 *
 * Радиус во всех вариантах заведомо больше половины стороны, то есть это круг.
 *
 * ## Три крупных буквенных размера не перенесены
 *
 * Кегли 28/32, 40/44 и 56/56 — это стили `Headers/… • ricotta`, `• cheddar` и
 * `• gouda`. **Те же самые ступени**, которые решение 30 объявило сайтовым
 * слоем на `ButtonNavigation`, и под которые админская шкала не расширяется.
 *
 * Поэтому применён уже принятый прецедент: перенесены размеры, легшие в шкалу
 * точно, остальные ждут сайтовой темы. Буква есть у 24, 32 и 40; у 56, 72 и 104
 * доступны иконка и фотография, которым текстовая ступень не нужна.
 *
 * **24 достижимых сочетания из 30.** Шесть отложенных — это `letter` на трёх
 * крупных размерах × две плотности.
 */
export const avatarVariants = cva(
  'relative inline-flex shrink-0 items-center justify-center overflow-hidden rounded-full font-bold',
  {
    variants: {
      variant: {
        solid: 'bg-primary text-primary-foreground',
        // Мягкая ступень — та же, что у подложки таймера и нижнего стопа спиннера.
        soft: 'bg-primary/[var(--opacity-soft)] text-primary',
      },
      size: {
        24: 'size-6 text-xs',
        32: 'size-8 text-base',
        40: 'size-10 text-xl',
        // У крупных текстовой ступени нет — см. решение 30.
        56: 'size-14',
        72: 'size-18',
        104: 'size-26',
      },
    },
    defaultVariants: {
      variant: 'solid',
      size: 40,
    },
  },
)

/** Сторона глифа по размеру аватара. Лестница снята с мастера поштучно. */
export const avatarIcon: Record<number, number> = {
  24: 16,
  32: 16,
  40: 16,
  56: 20,
  72: 32,
  104: 56,
}

/** Размеры, у которых в мастере нарисована буква. Остальные — решение 30. */
export const avatarLetterSizes = [24, 32, 40] as const

export type AvatarVariants = VariantProps<typeof avatarVariants>
