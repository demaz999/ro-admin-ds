<script setup lang="ts">
/**
 * Меню — мастер `Menu` `3499:24661`, спека `832:20679`, тёмный набор `1810:18826`.
 *
 * Корень: вертикальный стек пунктов и ничего больше. Паддингов у контейнера нет
 * вовсе, зазор 2. Ширина идёт за режимом — 296 в обычном, 56 в компактном, те же
 * значения, что у самого пункта.
 *
 * ## Матрица целиком: 2 варианта
 *
 * Единственная ось — `Compact`. Она не про размер, а про **подачу**: в обычном
 * режиме пункт показывает иконку, подпись и счётчик, в компактном остаётся одна
 * иконка, а счётчик вырождается в точку. Подменю в компактном режиме не
 * разворачивается внутри полосы, а уезжает плашкой — `MenuPopover`.
 *
 * Режим задаётся здесь и пробрасывается вниз, чтобы каждый пункт не выставляли
 * руками: `Compact` у Атома — свойство всего меню, а не отдельной строки.
 *
 * ## Меню тёмное — но не потому, что тёмное у Атома
 *
 * Мастер нарисован на белом. Тёмным меню делает **тема**: в rososmotr сайдбар
 * тёмный при светлом интерфейсе. С мастера сюда пришли состав, геометрия и
 * механика состояний, цвет — из `sidebar-*`.
 */
import { provide, toRef } from 'vue'

const props = withDefaults(defineProps<{
  /** Ось `Compact` мастера. Пробрасывается всем пунктам внутри. */
  compact?: boolean
}>(), { compact: false })

/** Режим меню читают вложенные пункты, чтобы его не выставляли на каждом. */
provide('menuCompact', toRef(props, 'compact'))
</script>

<template>
  <nav
    data-slot="menu"
    class="flex flex-col gap-0.5 bg-sidebar text-sidebar-foreground"
    :class="props.compact ? 'w-14' : 'w-74'"
  >
    <slot />
  </nav>
</template>
