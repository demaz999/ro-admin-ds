import type { VariantProps } from 'class-variance-authority'
import { cva } from 'class-variance-authority'

export { default as ListRow } from './ListRow.vue'

/**
 * Строка-плашка — мастер `Plank` `1910:12739`, спека `8725:65781`.
 *
 * «Плашка» — жаргон; роль называется строкой списка с иконкой, аватаром и двумя
 * подписями. Соответствие имён — в `docs/naming.md`.
 *
 * ## Матрица целиком: 9 вариантов
 *
 * `Type` (3) × `Disabled` × `Active` дают формально двенадцать сочетаний,
 * нарисовано девять: **активной выключенной не бывает** — ровно как у пункта
 * меню не бывает выключенного выбранного.
 *
 * Ось `Type` — это содержимое **левого слота**, а не стиль строки: стрелка,
 * иконка или число. Коробка слота одна и та же во всех трёх, 44×32.
 *
 * ## Заливка устроена наоборот привычного
 *
 * У большинства компонентов активное состояние выделяется цветом на спокойном
 * фоне. Здесь наоборот: **в покое плашка приглушённая, а активная — белая.**
 *
 * | состояние | заливка | прозрачность узла |
 * |---|---|---|
 * | покой | приглушённая нейтраль | 1 |
 * | активная | **белая** | 1 |
 * | выключенная | приглушённая нейтраль | **0.48** |
 *
 * Поэтому роли две (`--row` и `--row-active`), а не «заливка плюс состояние»:
 * активная строка всплывает над фоном, а не подсвечивается.
 *
 * > **Выключенное здесь 0.48, а не 0.32.** У Атома два уровня гашения, и они не
 * > взаимозаменяемы: кнопки и вкладки гаснут до 0.32, поля и контролы выбора —
 * > до 0.48. Строка-плашка идёт по второму. Наблюдение было записано ещё в
 * > волне 3 как факт без вывода; здесь оно подтвердилось замером.
 *
 * ## Геометрия
 *
 * Высота 64, радиус 16, паддинг справа 16, слева нет вовсе — его отдаёт левый
 * слот. Зазор 8. Ширина в мастере 270 — это размер демонстрационного узла:
 * оси размера нет, ширину задаёт контейнер.
 */
export const listRowVariants = cva(
  'flex h-16 w-full items-center gap-2 rounded-xl pr-4 text-left outline-none disabled:pointer-events-none disabled:opacity-[var(--opacity-disabled)]',
  {
    variants: {
      active: {
        true: 'bg-row-active',
        false: 'bg-row',
      },
    },
    defaultVariants: { active: false },
  },
)

export type ListRowVariants = VariantProps<typeof listRowVariants>
