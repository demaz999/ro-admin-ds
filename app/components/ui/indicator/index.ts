/**
 * Индикатор — мастер `Bulb` `790:10402`, спека `1858:11709`, тёмный набор `6976:58825`.
 *
 * «Лампочка» ничего не говорит о роли: это точка-метка и счётчик. Имя в коде —
 * `Indicator`, соответствие зафиксировано в `docs/naming.md`.
 *
 * ## Состояний нет — и это объявлено, а не пропущено
 *
 * Спека `1858:11709` подписана буквально: **«Неинтерактивный компонент»**. Ни
 * hover, ни pressed, ни disabled у индикатора не существует, и искать их в
 * мастере не нужно. Это единственный компонент кита, где двухчастное правило
 * закрывается одной строкой спеки.
 *
 * ## Матрица мастера — не полный крест
 *
 * 47 вариантов складываются из трёх неодинаковых блоков:
 *
 * | `Type` | размеров | цветов | вариантов |
 * |---|---|---|---|
 * | `shape` — голая точка | 2 | 9 | 18 |
 * | `text` — только цифра | 2 | **10** (плюс белый) | 20 |
 * | `shape+text` — счётчик в плашке | **1**, только крупный | 9 | 9 |
 *
 * Белого нет у точки и у счётчика, малого размера нет у счётчика. В коде это
 * повторено: `inverse` доступен только у `text`, а `counter` игнорирует `size`.
 *
 * ## Что стало с цветовой осью
 *
 * Девять цветовых колонок осью не переносятся (решение 23). Но индикатор —
 * первый компонент, где цвет несёт **смысл**: точка статуса без цвета статуса
 * не работает. Поэтому колонки сведены к нашим семантическим ролям, а не
 * перенесены поштучно: 47 вариантов мастера дают 27 достижимых сочетаний.
 * Разбор — `docs/waves.md`, отдельной строкой.
 *
 * ## Геометрия
 *
 * | | `md` | `sm` |
 * |---|---|---|
 * | точка | 12×12 | 8×8 |
 * | кегль | 13/16 Medium | 10/12 Regular |
 *
 * Радиус точки в мастере — 6 при стороне 12 и 4 при стороне 8, то есть ровно
 * половина: это круг, а не скруглённый квадрат. Свечение — тень 0/2/8 в цвете
 * самой точки на 64%.
 *
 * Счётчик: высота 16, радиус 8 (снова половина — плашка-пилюля), паддинг 4 по
 * горизонтали, минимальная ширина 16, чтобы одиночная цифра давала круг.
 *
 * > **Артефакт мастера.** Внутри счётчика лежит прямоугольник 8×1, залитый
 * > цветом самой плашки, — невидимый распорщик, который и даёт асимметричные
 * > паддинги 1 сверху и 2 снизу. В коде он не воспроизводится: коробка задана
 * > высотой 16 напрямую. Отдано дизайнерам строкой в `docs/figma-fixes.md`.
 */
export const indicatorVariants = cva('inline-flex shrink-0 items-center justify-center', {
  variants: {
    variant: {
      default: 'text-primary',
      success: 'text-success',
      warning: 'text-warning',
      destructive: 'text-destructive',
      neutral: 'text-muted-foreground',
      /** Только для `type="text"`: белой точки и белого счётчика в мастере нет. */
      inverse: 'text-primary-foreground',
    },
    type: {
      // Точка красится `bg-current`, поэтому свечение берёт тот же цвет.
      dot: 'rounded-full bg-current shadow-indicator',
      text: 'font-medium',
      /**
       * Счётчик — единственный, у кого цвет роли уходит в ЗАЛИВКУ. Роль остаётся
       * на `text-*`, заливка берёт её через `bg-current`, а сама подпись
       * перекрашивается в белый уже внутри, отдельным узлом: покрасить контейнер
       * белым здесь значило бы стереть роль и получить белое на белом.
       */
      counter: 'h-4 min-w-4 rounded-md bg-current px-1 text-3xs font-normal',
    },
    size: {
      md: '',
      sm: '',
    },
  },
  compoundVariants: [
    { type: 'dot', size: 'md', class: 'size-3' },
    { type: 'dot', size: 'sm', class: 'size-2' },
    { type: 'text', size: 'md', class: 'text-xs' },
    // 10/12 — ступень Атома, в шкале кита 1 её не было. Заведена по стилю мастера.
    { type: 'text', size: 'sm', class: 'text-3xs font-normal' },
  ],
  defaultVariants: {
    variant: 'default',
    type: 'dot',
    size: 'md',
  },
})

export type IndicatorVariants = VariantProps<typeof indicatorVariants>
