import type { VariantProps } from 'class-variance-authority'
import { cva } from 'class-variance-authority'

export { default as Alert } from './Alert.vue'

/**
 * Уведомление — мастер `Notification` `5883:58974`, спека `5883:55689`,
 * тёмный набор `6427:59239`.
 *
 * Имя в коде — `Alert`: описание мастера прямо задаёт роль — «всплывает в правом
 * верхнем углу, на брейкпоинте narrow растягивается на всю ширину». Позиционирование
 * и очередь показа — забота страницы, а не компонента; здесь только плашка.
 *
 * > **Всплывающего `Toast` в Атоме нет.** Это одиночная плашка без состояний,
 * > без стека и без анимации входа. Отсутствие, а не противоречие: строка в
 * > `docs/design-debt.md`, закрытие дефолтом shadcn-vue на этапе 2.
 *
 * ## Матрица целиком: 3 варианта
 *
 * Оси мастера — `Type` (`default` | `timer`) × `Show icon`. Формально 4
 * сочетания, нарисовано 3: у `timer` вариант без иконки не существует, потому
 * что таймер и есть иконка — он занимает то же место слева.
 *
 * | вариант | node id | иконка | крестик |
 * |---|---|---|---|
 * | `default`, без иконки | `5912:53121` | нет | есть |
 * | `default`, с иконкой | `5883:58969` | 16×16 | есть |
 * | `timer` | `5883:58975` | кольцо 20×20 | **нет** |
 *
 * Крестик и таймер взаимоисключающи: таймер закрывает плашку сам, поэтому
 * закрыть её вручную нельзя. Это состав мастера, а не наше упрощение.
 *
 * ## Геометрия
 *
 * Ширина 360, радиус 12, заливка белая, тень `BigShadow` — та же, что у
 * выпадашки. Зазор 12, вертикальный паддинг 12. Горизонтальный **зависит от
 * варианта**, потому что крестик и иконка съедают поля по-разному:
 *
 * | вариант | слева | справа |
 * |---|---|---|
 * | `default`, без иконки | 20 | 40 |
 * | `default`, с иконкой | 16 | 40 |
 * | `timer` | 16 | 20 |
 *
 * Текст 16/20 Regular, действие под ним — `ButtonAction` 16/20 Medium с зазором 4.
 * Крестик 8×8 прибит абсолютно в 12 от верха и правого края.
 */
export const alertVariants = cva(
  'relative flex w-90 items-start gap-3 rounded-lg bg-popover py-3 text-base text-popover-foreground shadow-dropdown',
  {
    variants: {
      type: {
        default: '',
        // Правое поле уже: крестика у таймера нет, место под него не резервируется.
        timer: 'pr-5',
      },
      showIcon: {
        // Паддинг слева отличается на 4: иконка добирает поле собственной рамкой.
        true: 'pl-4',
        false: 'pl-5',
      },
    },
    compoundVariants: [
      { type: 'default', class: 'pr-10' },
    ],
    defaultVariants: {
      type: 'default',
      showIcon: false,
    },
  },
)

export type AlertVariants = VariantProps<typeof alertVariants>
