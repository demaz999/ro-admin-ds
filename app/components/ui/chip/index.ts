import type { VariantProps } from 'class-variance-authority'
import { cva } from 'class-variance-authority'

export { default as Chip } from './Chip.vue'

/**
 * Фильтр-чип — **фаза обогащения, очередь 2**.
 *
 * ## Источник двойной, и обе половины названы
 *
 * | Что | Откуда |
 * |---|---|
 * | состав, геометрия, типографика, счётчик, крестик | мастер `badge` `747:2464` **кита 1**, файл `uG3HTIcMwr2jI2d7YEYPs2` |
 * | ось `active`, маркер-точка | `ButtonTag` `256:3601` **Атома** — по карте «компонент → источник состава» в `docs/atom-audit.md` |
 *
 * Эталон — экспорт мастера 1x: `public/compare/kit1/chip_747-2464.png`, 149×32.
 *
 * > **Мастер кита 1 жив.** Задание на очередь 2 предполагало реконструкцию по
 * > справочнику значений, потому что исходника нет. Замер показал обратное:
 * > `747:2464` на месте, 149×32, страница `🟢 Badge`. Поэтому здесь обычный
 * > перенос с наложением, а не реконструкция. Разбор — `docs/waves.md`.
 *
 * ## Это не `Tag` и не `Badge`
 *
 * Три сущности под похожими именами, и путать их дорого:
 *
 * | | высота | снимается | считает |
 * |---|---|---|---|
 * | `Badge` `1173:196` | 24 | нет | нет |
 * | `Tag` `256:3601` (Атом) | 24 | **нет** | **нет** |
 * | `Chip` `747:2464` | **32** | **да**, крестиком | **да**, счётчиком |
 *
 * ## Геометрия — с мастера
 *
 * | что | значение |
 * |---|---|
 * | высота | 32 |
 * | радиус | 24 (`--radius-2xl`) |
 * | паддинг | 16 по горизонтали |
 * | зазор подпись ↔ крестик | 8 |
 * | зазор подпись ↔ счётчик | 4 |
 * | подпись | 15/20 **Regular** |
 * | счётчик | высота 16, радиус полный, паддинг 4, кегль **12/16 Bold** |
 * | коробка крестика | 16×16, видимый глиф **9.4** |
 *
 * Ширина мастера 149 складывается ровно: 16 + (73 + 4 + 16) + 8 + 16 + 16.
 *
 * ## Счётчик не переиспользует `Indicator`
 *
 * Соблазн есть: `Indicator type="counter"` — тоже плашка высотой 16 с паддингом
 * 4. Но её типографика атомовская — 13/16 Medium, — а у чипа кита 1 стоит
 * 12/16 **Bold**. Подстановка утащила бы в компонент кита 1 кегль Атома, и
 * наложение разошлось бы на цифре. Счётчик собран здесь по мастеру.
 *
 * ## Крестик: бокс с мастера, глиф с мастера
 *
 * У кита 1 пикта `20_ic_close` живёт в коробке 16×16, а её видимый контур —
 * 9.4×9.4, то есть глиф свой бокс **не** заполняет. Это противоположность
 * правилу Атома («глиф заполняет бокс по доминирующей стороне»), поэтому здесь
 * размер иконки задан по видимому контуру эталона, а не по коробке: `size` 9.4
 * внутри контейнера 16. Автопроверка оптики при этом остаётся зелёной — она
 * сверяет глиф с собственным боксом `svg`, а не с контейнером.
 *
 * ## Чего в мастере нет
 *
 * Ни наведения, ни нажатия, ни выключенного состояния: `747:2464` — одиночный
 * `COMPONENT`, вариантов у него нет вовсе, а спек-страниц кит 1 не ведёт.
 * Строка в `docs/design-debt.md`; закрыто дефолтом по аналогии с уже
 * перенесённым, помечено `@debt` в `Chip.vue`.
 */
export const chipVariants = cva(
  'inline-flex h-8 w-fit shrink-0 items-center gap-2 rounded-2xl px-4 text-sm whitespace-nowrap select-none',
  {
    variants: {
      /**
       * Ось `Active` пришла из `ButtonTag` Атома: у чипа кита 1 её нет, а
       * фильтр без включённого состояния не работает. Механика взята оттуда же —
       * заливка становится брендовой, подпись белой.
       */
      active: {
        true: 'bg-primary text-primary-foreground',
        false: 'bg-chip text-foreground',
      },
    },
    defaultVariants: { active: false },
  },
)

/**
 * Счётчик. В покое — брендовая заливка с белой цифрой, ровно как в мастере.
 *
 * @debt Во включённом состоянии заливка чипа сама становится брендовой, и
 * счётчик слился бы с ней в одно пятно. Инверсия выведена по механике маркера
 * `Tag` (на активном он тоже уходит в белый), а не нарисована в ките.
 */
export const chipCounterVariants = cva(
  'inline-flex h-4 min-w-4 shrink-0 items-center justify-center rounded-full px-1 text-2xs font-bold',
  {
    variants: {
      active: {
        true: 'bg-primary-foreground text-primary',
        false: 'bg-primary text-primary-foreground',
      },
    },
    defaultVariants: { active: false },
  },
)

export type ChipVariants = VariantProps<typeof chipVariants>
