import type { VariantProps } from 'class-variance-authority'
import { cva } from 'class-variance-authority'

export { default as NavigationTile } from './NavigationTile.vue'

/**
 * Навигационная плитка — мастер `NavigationTile` `638:5476`, спека `619:5264`.
 *
 * Крупная карточка-ссылка в раздел: белая плашка с заголовком. Не пункт меню и
 * не строка списка — она живёт на странице, а не в навигационной панели.
 *
 * ## Матрица целиком: 2 варианта
 *
 * Единственная ось — `Breakpoint`, и она **не размер, а точка перелома**:
 *
 * | вариант | габарит | кегль |
 * |---|---|---|
 * | `Narrow&middle` | 153×204 | 16 Bold |
 * | `Wide` | 212×282 | 20 Bold |
 *
 * Имя оси в коде не переносится: `Breakpoint` описывает, при какой ширине окна
 * вариант применяется, а компонент про это не знает. В коде это `size` со
 * значениями `md` и `lg`, а выбор делает раскладка страницы.
 *
 * > В соседних мастерах та же ось написана с опечаткой — `Brakepoint`
 * > (`Announcement` `149:1663`, `MediaGallery` `6734:62674`). Здесь написание
 * > верное; разнобой отдан дизайнерам.
 *
 * Радиус 16, заливка белая, собственных паддингов у контейнера нет.
 *
 * ## Габариты не переносятся, и это решение, а не пропуск
 *
 * В мастере коробки 153×204 и 212×282. Ни одна сторона не лежит на шкале
 * кратности четырём, и это не случайность: **у Figma нет резиновой раскладки**,
 * поэтому два варианта — это два снимка одной плитки на разных ширинах окна, а
 * не два её размера.
 *
 * Зашить 153px значило бы получить плитку, которая не тянется, — то есть
 * воспроизвести ограничение инструмента, а не замысел. Поэтому в код перенесены
 * **радиус, заливка и типографика**, а коробку задаёт сетка страницы.
 *
 * Отклонение сознательное, записано в `docs/figma-fixes.md`.
 */
export const navigationTileVariants = cva(
  'flex flex-col justify-end rounded-xl bg-card text-left font-bold text-card-foreground outline-none',
  {
    variants: {
      size: {
        // Различие вариантов — только кегль: коробку задаёт сетка страницы.
        md: 'text-base',
        lg: 'text-xl',
      },
    },
    defaultVariants: { size: 'md' },
  },
)

export type NavigationTileVariants = VariantProps<typeof navigationTileVariants>
