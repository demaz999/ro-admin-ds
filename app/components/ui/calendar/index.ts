/**
 * Календарь — мастер `DatePickerPopOver` `1159:10888`, спека `1154:9417`.
 *
 * ## Ось `Popover` — это «плашка или врезка», а не вид календаря
 *
 * | значение | габарит | заливка | паддинг |
 * |---|---|---|---|
 * | `true` | 280×264 | белая, тень `0 / 8 / 32` | 20 |
 * | `false` | 280×224 | **нет** | 0 |
 *
 * То есть при `false` остаётся голая сетка, которую кладут во что-то своё, а при
 * `true` она обёрнута в ту же плашку, что выпадашка списка и подменю. Поэтому в
 * коде календарь — **сетка**, а плашку даёт `Popover`: собирать её третий раз
 * незачем.
 *
 * ## Ось `Range` на контейнер не влияет
 *
 * Проверено замером: `Range=true` и `Range=false` дают **одинаковые** габариты
 * и одинаковые размеры детей. Ось меняет только отрисовку выделения внутри
 * сетки — в коде это `range`, а не отдельный вид.
 *
 * > **Непоследовательность.** У `Range=false, Popover=false` тень есть, а у
 * > `Range=true, Popover=false` её нет — при том, что заливки нет у обоих.
 * > Тень на фрейме без заливки бессмысленна и отличается между значениями оси,
 * > которая на контейнер не влияет. Отдано дизайнерам.
 *
 * ## Геометрия
 *
 * | часть | значение |
 * |---|---|
 * | ширина сетки | 240 |
 * | шапка «месяц и год» | 240×20, стрелки по краям, подпись посередине |
 * | строка дней недели | 240×16, семь ячеек |
 * | неделя | 240×24, семь ячеек 24×24, зазор между строками 4 |
 * | ячейка дня | 24×24, кегль 13 Medium |
 * | недель в сетке | **6**, всегда |
 *
 * Шесть строк нарисованы всегда, независимо от месяца: сетка не скачет по высоте
 * при перелистывании. Это состав мастера, а не наша добавка.
 */
