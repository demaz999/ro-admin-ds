import type { VariantProps } from 'class-variance-authority'
import { cva } from 'class-variance-authority'

export { default as Timer } from './Timer.vue'

/**
 * Таймер — мастер `Timer` `6344:55714`, спека `6340:55580`, тёмный набор `6395:55793`.
 *
 * Описание мастера задаёт роль: «через заданное время выполняет нужное действие,
 * например, закрытие уведомления». То есть это **индикатор обратного отсчёта**,
 * а не спиннер: у спиннера конца нет, у таймера он и есть смысл.
 *
 * ## Матрица целиком: 6 вариантов
 *
 * Оси `Number` × `Size` (3) — полный крест, все шесть нарисованы.
 *
 * | `Size` в мастере | сторона | в коде |
 * |---|---|---|
 * | `echemeia` | 20 | `sm` |
 * | `menolorice` | 32 | `md` |
 * | `aethusa` | 48 | `lg` |
 *
 * ## Это кольцо. Волна 4 сказала «сектор» — и ошиблась
 *
 * Первый разбор смотрел на **структуру узлов**: внутри два вектора, `Bg` во всю
 * сторону и `Timer` поменьше, дырки в дереве не видно — отсюда вывод «сектор».
 * Вывод был неверный: вектор может быть кольцом сам по себе, и структура этого
 * не показывает.
 *
 * Проверка экспортом, которую следовало сделать сразу, даёт однозначное:
 * центральная строка экспорта 48px читается как `[7](13)[8](13)[7]` — стенка
 * кольца, пустота, цифра, пустота, стенка. Середина **белая**, и цифра лежит
 * именно в ней.
 *
 * | сторона | 20 | 32 | 48 |
 * |---|---|---|---|
 * | стенка кольца | 4 | 5 | 7 |
 * | отверстие | 12 | 22 | 34 |
 *
 * Толщина непропорциональна стороне — та же лесенка, что у `Spinner` и у глифа
 * `Avatar`.
 *
 * > **Отсюда же и «нечитаемая цифра».** Она не про цвет: цифра брендовая и в
 * > мастере, и у нас. Пока сектор был залит целиком, цифра ложилась на брендовую
 * > заливку. В кольце она лежит в отверстии на фоне подложки и читается без
 * > всякого правила контраста — такого правила в мастере и нет, проверено по
 * > всем трём размерам.
 *
 * Урок записан в `docs/atom-inconsistencies.md`: **структура узлов не заменяет
 * экспорт.** `CLAUDE.md` требует сверяться с экспортом при любом сомнении
 * «показано или нет» — здесь сомнения не возникло, и в этом была ошибка.
 */
export const timerVariants = cva('relative inline-flex shrink-0 items-center justify-center rounded-full text-primary', {
  variants: {
    size: {
      sm: 'size-5',
      md: 'size-8 text-xs font-medium',
      lg: 'size-12 text-base font-medium',
    },
  },
  defaultVariants: { size: 'lg' },
})

/** Толщина стенки кольца в пикселях. Замерено по экспорту мастера `6344:55714`. */
export const timerRing: Record<NonNullable<TimerVariants['size']> & string, number> = {
  sm: 4,
  md: 5,
  lg: 7,
}

export type TimerVariants = VariantProps<typeof timerVariants>
