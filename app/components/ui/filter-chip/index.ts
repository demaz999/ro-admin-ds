/**
 * Чип применённого фильтра — **такт 3 сборки страницы, правка 18**.
 *
 * ## Почему производный компонент, а не третий вид `Chip`
 *
 * `Chip` — это одна пилюля: подпись, счётчик, хвостовой контрол. Здесь же к
 * пилюле привязан **список значений в поповере со снятием по одному** и ссылка
 * сброса. Это уже не вид чипа, а связка «чип + выпадашка + список» — ровно та
 * же ситуация, что у `Breadcrumb`, собранного из `ButtonNavigation`:
 * композиция получает своё имя, а не ось внутри детали.
 *
 * Поэтому `Chip` расширен минимально — осью хвостового контрола, — а вся
 * механика раскрытия живёт здесь.
 *
 * ## Три вида одним компонентом
 *
 * Вид выводится из данных, а не задаётся пропом: чип отражает состояние
 * фильтра, и автор страницы не должен выбирать его вид руками.
 *
 * | Данные | Что показывает | Хвост |
 * |---|---|---|
 * | одно значение | подпись значения | крестик |
 * | `range` | название и диапазон | крестик |
 * | больше одного значения | название и счётчик | шеврон, по клику список |
 *
 * ## Что внутри — только реестр
 *
 * `Chip` даёт пилюлю и счётчик, `Popover` — плашку, `SelectItem` — строку
 * значения, `IconButton` — крестик в строке, `ButtonAction` — «Сбросить все».
 * Ни одного своего цвета, радиуса или кегля.
 *
 * Плашка позиционируется композицией — тем же приёмом, что календарь внутри
 * `DatePicker` и меню массовых действий на пилотной странице.
 */
