<script setup lang="ts">
/**
 * Подменю, выехавшее вбок — мастер `MenuPopOver` `3499:27440`, спека `832:20679`.
 *
 * В компактном режиме вложенный список некуда развернуть внутри полосы 56
 * шириной, поэтому он уезжает плашкой вбок. Это тот же второй уровень, что у
 * `MenuSub`, но в другой подаче.
 *
 * ## Правило порталов соблюдается здесь буквально
 *
 * Плашка вылетает из тёмного меню — и она **светлая**: заливка белая, тень
 * `0 / 8 / 32`, то есть ровно та же, что у выпадашки списка. Внутри неё
 * `sidebar-*` не действуют; это обычные светлые токены поповера.
 *
 * Проверено по мастеру, а не принято по правилу: заливка `#ffffff`, эффект
 * `DROP_SHADOW 0/8 r32 #0c10181f` — совпадает с `--shadow-dropdown` бит в бит.
 *
 * ## Матрица целиком: 4 варианта
 *
 * `Icons` × `Scroll` — полный крест. Ось `Icons` управляет иконками у строк
 * внутри, то есть пробрасывается в них, а не меняет саму плашку.
 *
 * Ось `Scroll` меняет **паддинг контейнера**: без прокрутки 4 со всех сторон и
 * зазор 2, с прокруткой — 4 только слева и зазор 0, потому что отступы забирает
 * область прокрутки вместе с дорожкой бегунка.
 *
 * Ширина 240, радиус 12. Высота 190 в мастере — размер демонстрационного узла,
 * а не ограничение: оси размера нет, высоту задаёт содержимое.
 */
const props = withDefaults(defineProps<{
  /** Ось `Scroll` мастера: содержимое прокручивается, паддинги отдаёт дорожке. */
  scroll?: boolean
  /** Ширина из мастера. */
  width?: number
}>(), {
  scroll: false,
  width: 240,
})
</script>

<template>
  <div
    data-slot="menu-popover"
    class="rounded-lg bg-popover shadow-dropdown"
    :class="props.scroll ? 'pl-1' : 'p-1'"
    :style="{ width: `${props.width}px` }"
  >
    <div
      class="flex flex-col"
      :class="props.scroll ? 'max-h-full gap-0 overflow-y-auto' : 'gap-0.5'"
    >
      <slot />
    </div>
  </div>
</template>
