<script setup lang="ts">
import { cn } from '@/lib/utils'

/**
 * Панель действий над таблицей — **верхняя часть того же контейнера**.
 *
 * Источник — `table_header` `19601:29062` кита 1: заливка `accent/surface_soft`,
 * паддинг 16, высота 76 и **явные верхние углы 16**. В макете дашборда эта
 * панель входит внутрь фрейма `table` `19601:29061` вместе с телом и подвалом,
 * то есть container = панель + таблица + подвал под одной рамкой.
 *
 * ## Почему компонент, а не панель на странице
 *
 * У «Мои осмотры» такая панель вынесена **наружу** решением владельца от
 * 2026-08-18: она общая для плитки и таблицы, а таблицы в плитке нет. Там это
 * оправдано. Там же, где вид один — как на «Типы схем осмотров», — панель
 * возвращается на своё место из макета, и тогда верхние углы и рамку несёт
 * она, а `Table` получает `attached-top`.
 *
 * Оба варианта законны, но выбор не должен каждый раз собираться из классов на
 * странице: иначе рамка и радиус разъедутся между экранами.
 */
const props = defineProps<{ class?: string }>()
</script>

<template>
  <div
    data-slot="table-toolbar"
    :class="cn(
      'flex h-19 shrink-0 items-center gap-4 rounded-t-xl border border-b-0 border-border-soft bg-secondary px-4',
      props.class,
    )"
