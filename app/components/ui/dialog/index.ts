/**
 * Модальное окно — **очередь 3 этапа 2**.
 *
 * ## Провенанс: композиция, а не мастер
 *
 * Мастера модального окна в Атоме нет. Есть страница `ModalWindow` и на ней
 * три композиции из инстансов — это и есть источник:
 *
 * | Узел | Что это |
 * |---|---|
 * | `1156:10007` | раскладочная спека: восемь схем на трёх ширинах, с сеткой и плашками «Content area» / «Controls area» |
 * | `6626:56959` | **живой пример** окна целиком: заголовок, текст, две кнопки, возврат, крестик |
 * | `1204:9799` | тёмный близнец раскладочной спеки |
 *
 * Провенанс каждого значения — **композиция**, а не мастер. Это слабее обычного
 * источника: у композиции нет осей, нет состояний и некому гарантировать, что
 * два инстанса не разошлись. Поэтому расхождения между спекой и примером
 * записаны, а не усреднены — см. `docs/atom-inconsistencies.md`.
 *
 * ## Окно занимает экран целиком
 *
 * Главное расхождение с дефолтом shadcn, и оно снято прямо с подписи на
 * странице: **«Модальные окна отображаются в полный экран на белом непрозрачном
 * фоне»**. Ни карточки по центру, ни затемняющей подложки в композиции нет —
 * поэтому `DialogOverlay` не рисуется вовсе, а `--overlay` остаётся токеном
 * поповеров и лайтбокса.
 *
 * `wide` / `middle` / `narrow` в спеке — это **ширины экрана**, а не размеры
 * окна: подпись рядом с ними гласит «Всегда вся ширина экрана». Оси размера у
 * компонента поэтому нет.
 *
 * ## Геометрия
 *
 * Три величины меняются вместе с шириной экрана — это одна и та же лесенка:
 *
 * | | narrow 320 | middle 598 | wide 1024+ |
 * |---|---|---|---|
 * | боковой паддинг | 24 | 32 | 40 |
 * | высота шапки | 44 | 44 | 60 |
 * | отступ крестика | 2 | 2 | 10 |
 *
 * Отступ крестика не произвольный: кнопка 40×40 центрируется в шапке, то есть
 * `(высота шапки − 40) / 2`. Так и реализовано.
 *
 * **Колонка контента — 8 из 12 колонок сетки, гуттер 32.** Проверено на двух
 * ширинах: при 1360 колонка 842, при 1024 — 618. Обе сходятся точно, без
 * подгонки: `(ширина − 2×паддинг − 11×32) / 12 × 8 + 7×32`. Поэтому в коде
 * стоит настоящая двенадцатиколоночная сетка, а не выведенный процент.
 *
 * Вертикальный ритм колонки, с примера `6626:56959`: иконка → заголовок 24,
 * заголовок → текст 16, текст → кнопки 32.
 *
 * ## Футер существует, и он с прокруткой
 *
 * Долг «у Dialog нет тела и футера» тянулся с волны 1. Футер нашёлся: в четырёх
 * схемах из восьми лежит группа `Button-block` — 96 высотой, во всю ширину, с
 * непрозрачной заливкой той же поверхности. Она **прижата к низу и лежит
 * поверх** прокручиваемого контента: в схемах со скроллом плашка контента
 * уходит под неё.
 *
 * Кнопки внутри блока 40 высотой, отступ сверху 24.
 */
